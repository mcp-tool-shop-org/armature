"""Land 33 MediaPipe-topology landmarks on the 22-bone rig, as rotations. No bpy, no numpy.

The missing tool in the clean chain. A video model generates a performance; MediaPipe
regresses 33 world landmarks per frame; **this module turns those positions into joint
rotations on the performer's own skeleton.** `tools/lift_solve.py` is the Blender-side
applier; everything decidable without Blender is decided here, so its tests run in
milliseconds and its arithmetic can be checked against mathematics rather than against a
render.

--------------------------------------------------------------------------------
Why this is a rotation solve and not a retarget

Positions do not determine rotations. A limb segment's direction fixes two of a bone's
three rotational degrees of freedom; the third — twist about the segment's own axis —
leaves every landmark on that segment exactly where it was. G16 in
`docs/research-grounding-e08.md` says this in the literature's words: *positions
underdetermine twist*, so a position-only stream needs a separate rotation solve with
pole/twist references rather than an endpoint fit.

So every bone here is solved as **swing + twist**, and the swing is a measurement: the
observed segment direction fixes it outright. The twist is not, and the distinction is
worth stating exactly because it is easy to get backwards.

**A parent's twist is invisible to positions even when it has a child.** Twisting the
upper arm about its own axis moves nothing on the upper arm and does not move the elbow;
the forearm can then be re-aimed at the observed wrist from the new frame, so every twist
angle explains the same landmarks. The twist becomes recoverable only under an added
**constraint**, and this module adds the anatomical one: *the child joint bends about a
fixed hinge axis carried from the bind pose* (`hinge_hint` in MODEL — the character's own
lateral axis, which is where an elbow and a knee actually hinge). The parent's twist is
then whatever carries that hinge axis onto the observed bend plane.

So `underdetermined` means one thing and the report must not blur it: **no bend, no
twist.** Where the child does not bend on a frame there is no bend plane, the constraint
says nothing, and the twist is set to zero and named rather than invented. Where a bone
has no child past its tail at all — a wrist with nothing past the hand, an ankle with
nothing past the toe — it is underdetermined on every frame. G16's sentence, made
mechanical.

--------------------------------------------------------------------------------
What the round trip proves, stated exactly, because it is easy to overclaim

Each bone's rotation is *constructed* to carry its rest direction onto its observed
direction. So `fk_sites(rest, solve_frame(rest, obs))` reproduces `obs` as an algebraic
identity — not as a fit — for every site the model determines, whenever

  (a) the observation was generated by this rig's own kinematics, and
  (b) the motion lies inside this module's parameterisation (see MODEL below).

That is what `tests/test_lift_solve.py` pins at 1e-9 of the character's own bbox diagonal.
It proves the **inversion is exact**. It does not prove the model is adequate, and those
are different claims:

* Where the observation comes from a *different* body — a detector regressing a generic
  adult — segment lengths disagree with the rig's and the reproduction carries a residual.
  That residual is the bone-length measurement (`bone_length_residuals`), not a defect.
* Where the authored motion used degrees of freedom this model does not carry (`spine`,
  `neck` — see MODEL), the solve folds them into their neighbours and the reproduction
  carries a residual there too. That is the **model gap**, and it is measured on the
  authored ground truth with no detector in the loop, so it can be told apart from
  detector noise.

Both residuals are quantities to report. Neither is a threshold this module owns.

--------------------------------------------------------------------------------
MODEL — what is solved, what is held, and why. This IS the mapping table.

The 33-landmark topology does not carry one landmark per rig bone, so three bones are
held at identity with the reason recorded rather than being handed a rotation invented to
fill the gap:

* **`spine` — HELD.** There is no mid-torso landmark between the hips and the shoulders in
  the 33. The whole pelvis→shoulder rotation is carried on `chest`, whose pivot is then
  fixed and whose solve is exact. Splitting it across `spine` and `chest` would need a
  quantity nothing observes.
* **`neck` — HELD.** The 33 give one head frame (nose + two ears), not two. All head
  orientation rides `head`.
* **the five facial markers (`nose`, `eye.*`, `ear.*`) — HELD.** Registered
  non-deforming in `sitelist`: no vertex is weighted to them, so a rotation on one cannot
  change a rendered pixel.

Fingers are unused — the performer has mitten hands — and so are the heels, the mouth
corners and the six eye points. Every unused index is listed in `UNUSED_LANDMARKS` with
its reason, because an omission nobody wrote down reads as an oversight later.
"""

import math

