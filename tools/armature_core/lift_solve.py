def round_trip_report(rest, obs, solved, diagonal, tol_frac=ROUND_TRIP_TOL_FRAC,
                      raise_on_fail=True):
    """Does the solve reproduce the positions it was solved from? · ANDON

    **This raises**, inside the module that did the solve, rather than returning a verdict
    for a shell chain to walk past. It is the one check that is a gate here: a solver that
    does not invert its own model is broken, and everything downstream would be quoted
    against a wrong pose while every other number looked reasonable.

    The tolerance is a fraction of the character's own bbox diagonal. `raise_on_fail` is
    NOT a skip flag — it exists so the *measurement* path can report a residual against a
    real detector, where the observation comes from another body and a residual is the
    thing being measured rather than a defect. The gate is armed on the synthetic path,
    which is the one whose invariant is exactness.
    """
    got = fk_sites(rest, solved)
    tol = tol_frac * diagonal
    per_site, worst = {}, {"site": None, "d": 0.0}
    for site in sorted(SITE_FROM_LANDMARK):
        if site not in got:
            continue
        d = _norm(_sub(got[site], obs[site]))
        per_site[site] = d
        if d > worst["d"]:
            worst = {"site": site, "d": d}
    ev = {"gate": "SOLVE", "tolerance": tol, "tolerance_frac_of_diagonal": tol_frac,
          "bbox_diagonal": diagonal, "worst": worst, "per_site": per_site,
          "n_sites": len(per_site),
          "note": ("distance between each observed site and where the solved rotations "
                   "put it; exact by construction when the observation came from this "
                   "rig's own kinematics inside this model")}
    if raise_on_fail and worst["d"] > tol:
        raise SolveGate(
            f"the solve does not reproduce the positions it was solved from: "
            f"{worst['d']:.12f} at site {worst['site']!r} against a tolerance of "
            f"{tol:.12f}. This is an inversion defect, never a number to tune toward", ev)
    ev["verdict"] = f"max {worst['d']:.3e} over {len(per_site)} sites (tolerance {tol:.3e})"
    return ev


def bone_length_residuals(rest, obs):
    """Per bone: how much longer or shorter the observed segment is than the rig's own.

    The measurement that says whether a lift is landing a *different body* on this
    skeleton. Reported per structure and as a fraction of that bone's own rest length —
    never as a length in metres, and never as one number for the whole figure.
    """
    out = {}
    for bone in _bones():
        rule = MODEL.get(bone.name)
        if not rule or rule[0] != "direction":
            continue
        tail = rule[1]
        head = bone.head
        if head not in obs or tail not in obs:
            continue
        rest_len = _norm(_sub(rest[tail], rest[head]))
        obs_len = _norm(_sub(obs[tail], obs[head]))
        if rest_len <= 0:
            raise SolveError(f"bone {bone.name!r} has zero rest length")
        out[bone.name] = {
            "rest_length": rest_len, "observed_length": obs_len,
            "residual_fraction": (obs_len - rest_len) / rest_len,
        }
    return out


def validate_motion_record(frames):
    """The solved frames are a contiguous run and every bone is present. · ANDON

    Lives here rather than in the Blender applier so it can be exercised without a render
    — the same split every other gate in this repo keeps. Both clauses guard failures that
    are silent downstream: a **gap** in the frame numbering gets filled by whatever pose
    the previous keyframe held, and a **missing bone** simply keeps its last rotation.
    Either produces a clip that plays, exports, and passes every count-based check, and
    the stutter reads as the lift being noisy rather than as a frame that never arrived.
    """
    if not frames:
        raise SolveGate("the motion record carries no frames", {"n": 0})
    for i, fr in enumerate(frames):
        if fr.get("frame") != i:
            raise SolveGate(
                f"the solved frames are not a contiguous run from 0: entry {i} says frame "
                f"{fr.get('frame')!r}. A gap filled by the neighbouring pose would play as "
                f"a stutter and be read as detector noise",
                {"index": i, "says": fr.get("frame"), "n": len(frames)})
        local = fr.get("local") or {}
        missing = [b for b in sitelist.ALL_NAMES if b not in local]
        if missing:
            raise SolveGate(
                f"frame {i} carries no rotation for {missing}; a bone left out here would "
                f"hold its previous pose while every gate downstream stayed green",
                {"frame": i, "missing": missing})
    return {"gate": "SOLVE", "n_frames": len(frames),
            "verdict": f"{len(frames)} contiguous frames, all {len(sitelist.ALL_NAMES)} "
                       f"registered bones present on each"}


def compare_rotations(solved_local, authored_local):
    """Per-bone geodesic angle between a solved rotation and an authored one, in degrees.

    Compared as matrices. Two Euler triples that differ can name the same orientation, and
    a report that subtracted them would print an error that is not one.
    """
    out = {}
    for name, want in authored_local.items():
        got = solved_local.get(name)
        if got is None:
            continue
        out[name] = geodesic_deg(want, got)
    return out
